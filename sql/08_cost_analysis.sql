-- Q19: Cumulative Running Total of Healthcare Expenditures
WITH monthly_expenditure AS (
    SELECT 
        DATE_TRUNC('month', start_time)::DATE AS spend_month,
        SUM(total_claim_cost) AS monthly_claims
    FROM raw_synthea.encounters
    GROUP BY DATE_TRUNC('month', start_time)
)
SELECT 
    spend_month,
    ROUND(monthly_claims, 2) AS monthly_claims,
    ROUND(SUM(monthly_claims) OVER (ORDER BY spend_month), 2) AS cumulative_running_total
FROM monthly_expenditure
ORDER BY spend_month;

-- Q35: Cost Concentration (The 90/10 Rule)
-- Business Question: What percentage of total healthcare expenditure is generated by the top 10% of patients?
WITH patient_totals AS (
    SELECT 
        patient_id,
        SUM(total_claim_cost) AS total_patient_cost
    FROM raw_synthea.encounters
    GROUP BY patient_id
),
ranked_patients AS (
    SELECT 
        patient_id,
        total_patient_cost,
        NTILE(10) OVER (ORDER BY total_patient_cost ASC) AS spend_decile
    FROM patient_totals
),
decile_summary AS (
    SELECT 
        spend_decile,
        COUNT(*) AS patient_count,
        SUM(total_patient_cost) AS decile_spend,
        (SELECT SUM(total_claim_cost) FROM raw_synthea.encounters) AS total_system_spend
    FROM ranked_patients
    GROUP BY spend_decile
)
SELECT 
    spend_decile,
    patient_count,
    ROUND(decile_spend, 2) AS decile_spend,
    ROUND(decile_spend * 100.0 / NULLIF(total_system_spend, 0), 2) AS pct_of_total_system_spend
FROM decile_summary
ORDER BY spend_decile DESC;

-- Q36: Out-of-Pocket Patient Liability Distribution Across Payers
SELECT 
    COALESCE(p.name, 'Uninsured / Self-Pay') AS payer_name,
    COUNT(e.encounter_id) AS total_encounters,
    ROUND(SUM(e.total_claim_cost), 2) AS total_claim_volume,
    ROUND(SUM(e.payer_coverage), 2) AS total_payer_coverage,
    ROUND(SUM(e.total_claim_cost - e.payer_coverage), 2) AS total_patient_out_of_pocket,
    ROUND(
        SUM(e.total_claim_cost - e.payer_coverage) * 100.0 / NULLIF(SUM(e.total_claim_cost), 0),
        2
    ) AS patient_liability_share_pct
FROM raw_synthea.encounters e
LEFT JOIN raw_synthea.payers p ON e.payer_id = p.payer_id
GROUP BY p.name
ORDER BY total_claim_volume DESC;
